'use strict';

// Build plans only. Attendance, earned pay and cash receipts are never fabricated.
Object.assign(Store, {
  salaryRenewal(project) {return this.data.salaryRenewals.find(r=>r.project===project);},
  salaryRenewalTemplate(project,today=U.todayStr(),data=this.data) {
    const plans=data.salaryMonths.filter(p=>p.project===project&&this.salaryPlanValid(p)).sort((a,b)=>a.month.localeCompare(b.month));
    return plans.find(p=>{const r=this.salaryRange(p);return r.start<=today&&r.end>=today;}) ||
      plans.filter(p=>this.salaryRange(p).start<=today).at(-1) || plans[0];
  },
  normalizeSalaryRenewals(data,legacy) {
    // Existing users explicitly requested automatic renewal for this project only.
    if(!legacy)return;
    const p=this.salaryRenewalTemplate('企业上班',U.todayStr(),data);
    if(p&&!data.salaryRenewals.some(r=>r.project===p.project))data.salaryRenewals.push({project:p.project,enabled:true,anchorMonth:p.month,skippedMonths:[]});
  },
  writeSalaryRenewalRule(data,project,enabled,plan) {
    let rule=data.salaryRenewals.find(r=>r.project===project);
    const template=plan || this.salaryRenewalTemplate(project,U.todayStr(),data);
    if(!template)throw new Error('请先保存这个项目的工资方案');
    if(!rule){rule={project,enabled,anchorMonth:template.month,skippedMonths:[]};data.salaryRenewals.push(rule);}
    else rule.enabled=enabled;
  },
  setSalaryRenewal(project,enabled) {
    if(typeof enabled!=='boolean')throw new Error('请选择是否自动续期');
    this.mutate(d=>this.writeSalaryRenewalRule(d,project,enabled));
  },
  noteSalaryPlanRemoved(data,plan) {
    const rule=data.salaryRenewals.find(r=>r.project===plan.project);if(!rule)return;
    if(!rule.skippedMonths.includes(plan.month))rule.skippedMonths.push(plan.month);
    if(!data.salaryMonths.some(p=>p.project===plan.project))rule.enabled=false;
  },
  validateSalaryRenewals(data) {
    const rules=data.salaryRenewals || [],month=m=>WorkCalendar.validMonth(m)&&m>='1901-01'&&m<='2099-12';
    if(!Array.isArray(rules)||new Set(rules.map(r=>r?.project)).size!==rules.length||rules.some(r=>!r||typeof r.project!=='string'||!r.project.trim()||r.project.length>40||typeof r.enabled!=='boolean'||!month(r.anchorMonth)||!Array.isArray(r.skippedMonths)||new Set(r.skippedMonths).size!==r.skippedMonths.length||!r.skippedMonths.every(month)))throw new Error('备份中的自动续期设置无效');
    for(const p of data.salaryMonths || [])if(p.autoGenerated!=null&&typeof p.autoGenerated!=='boolean')throw new Error('工资方案的自动生成标记无效');
  },
  previewSalaryRenewals(today=U.todayStr(),project) {
    if(!/^\d{4}-\d{2}-\d{2}$/.test(today)||U.dateStr(U.parseDate(today))!==today)throw new Error('续期日期无效');
    this.validateSalaryRenewals(this.data);
    const additions=[],updates=[],issues=[];
    const signature=p=>JSON.stringify([p.baseMinor,p.cycleStartDay||1,!!p.cycleConfirmed,p.employmentStart||'',p.calendar,p.dates]);
    for(const rule of this.data.salaryRenewals.filter(r=>r.enabled&&(!project||r.project===project))){
      const plans=this.data.salaryMonths.filter(p=>p.project===rule.project).slice().sort((a,b)=>a.month.localeCompare(b.month));
      const issue=(month,message)=>issues.push({project:rule.project,month,message});
      const first=plans.find(p=>p.month===rule.anchorMonth) || plans.filter(p=>p.month<rule.anchorMonth).at(-1) || plans[0];
      if(!first){issue(rule.anchorMonth,'没有可沿用的工资方案，请先添加一期');continue;}
      let month=U.ymShift(first.month,1);
      for(let step=0;step<1200;step++,month=U.ymShift(month,1)){
        const template=plans.filter(p=>p.month<month).sort((a,b)=>a.month.localeCompare(b.month)).at(-1);
        if(!template||!this.salaryPlanValid(template)){issue(month,'原工资方案无效，请核对计薪设置');break;}
        const cycle=template.cycleStartDay || 1,target=U.ymShift(WorkCalendar.monthFor(today,cycle),1);
        if(month>target)break;
        if(!template.cycleConfirmed){issue(month,'计薪区间尚未确认，请先核对计薪设置');break;}
        if(rule.skippedMonths.includes(month))continue;
        const current=plans.find(p=>p.month===month),range=WorkCalendar.period(month,cycle);
        // Only untouched, not-yet-started generated plans can follow a changed salary.
        if(current&&(!current.autoGenerated||this.salaryRange(current).start<=today||this.data.worktimes.some(w=>w.salaryMonthId===current.id)||this.data.transactions.some(t=>t.wageProject===rule.project&&t.wageMonth===month)))continue;
        if(!WorkCalendar.hasYear(range.start.slice(0,4))||!WorkCalendar.hasYear(range.end.slice(0,4))){issue(month,'该期法定节假日及调休尚未收录，更新应用后会继续生成');break;}
        const next={id:current?.id || U.id(),project:rule.project,month,baseMinor:template.baseMinor,cycleStartDay:cycle,cycleConfirmed:true,employmentStart:template.employmentStart || '',calendar:'cn',dates:WorkCalendar.rangeDates(range.start,range.end,'cn'),autoGenerated:true,autoSourceMonth:template.month};
        if(plans.some(p=>p.id!==next.id&&this.salaryRange(p).start<=range.end&&this.salaryRange(p).end>=range.start)){issue(month,'该期与已有区间重叠，请核对计薪周期');break;}
        if(current){if(signature(current)!==signature(next)){updates.push(next);plans[plans.indexOf(current)]=next;}}
        else {additions.push(next);plans.push(next);}
      }
    }
    return {additions,updates,issues};
  },
  renewSalaryPeriods(today=U.todayStr()) {
    const result=this.previewSalaryRenewals(today);
    if(result.additions.length||result.updates.length)this.mutate(d=>{
      d.salaryMonths.push(...result.additions);
      for(const next of result.updates)Object.assign(d.salaryMonths.find(p=>p.id===next.id),next);
    });
    return result;
  },
  salaryRenewalStatus(project,today=U.todayStr()) {
    const rule=this.salaryRenewal(project),template=this.salaryRenewalTemplate(project,today);
    const nextMonth=template?U.ymShift(WorkCalendar.monthFor(today,template.cycleStartDay||1),1):'';
    return {enabled:!!rule?.enabled,template,next:this.salaryPlanFor(project,nextMonth),skipped:!!rule?.skippedMonths.includes(nextMonth),issue:rule?.enabled?this.previewSalaryRenewals(today,project).issues[0]?.message || '':''};
  }
});
