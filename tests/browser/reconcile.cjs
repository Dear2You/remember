'use strict';

const assert = require('node:assert/strict');
const test = require('node:test');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');

test('信用账单截止日、手续费金额筛选、期初输错保留原余额', async t=>{
  const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL || undefined});
  t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:320,height:720},reducedMotion:'reduce'});
  await page.goto(pathToFileURL(path.resolve(process.env.APP_HTML || 'app/index.html')).href);
  const old='2026-03-31', next='2026-04-01';
  await page.evaluate(([old,next])=>{
    const common={bookId:'book-life',date:old};
    Store.updateAccount('acc-bank',{opening:10000});
    Store.addTransaction({...common,type:'out',accountId:'acc-credit',amountMinor:1980,note:'样例餐费'});
    Store.addTransaction({...common,type:'transfer',fromId:'acc-bank',toId:'acc-credit',amountMinor:1000,feeMinor:20,feeMode:'extra'});
    Store.addTransaction({...common,date:next,type:'out',accountId:'acc-credit',amountMinor:300,note:'次日消费'});
    Store.updateAccount('acc-credit',{archived:true});
  },[old,next]);
  const nav=route=>page.locator('#tabbar [data-route="'+route+'"]').click();
  const sheet=page.locator('#sheetRoot');
  const close=()=>sheet.locator('.sheet-close').click();
  await nav('assets');
  await page.locator('.j-toggle-debt').click();
  await page.getByRole('button',{name:/信用卡欠款.*已停用/}).click();
  assert.equal(await sheet.locator('.reconcile-balance').innerText(),'¥12.8');
  await sheet.getByLabel('核对截至日期').fill(old);
  assert.equal(await sheet.locator('.reconcile-balance').innerText(),'¥9.8');
  await sheet.locator('.j-real').fill('9.80');
  assert.equal(await sheet.locator('.j-difference').innerText(),'欠款一致');
  assert.equal(await sheet.locator('[data-review]').count(),2);
  await close();
  await page.locator('.asset-overview .j-mgr').click();
  await sheet.locator('.j-edit[data-id="acc-bank"]').click();
  await sheet.locator('.j-open').fill('1,23');
  await sheet.getByRole('button',{name:'保存修改'}).click();
  assert.equal(await page.evaluate(()=>Store.account('acc-bank').opening),10000);
  await sheet.locator('.j-open').fill('-0.05');
  await sheet.getByRole('button',{name:'保存修改'}).click();
  assert.equal(await page.evaluate(()=>Store.account('acc-bank').opening),-5);
  await sheet.getByPlaceholder('账户名称').fill('差旅信用卡');
  await sheet.locator('.j-open').fill('12.04');
  await sheet.locator('.j-type2 [data-t="liability"]').click();
  await sheet.getByRole('button',{name:'添加账户'}).click();
  assert.deepEqual(await page.evaluate(()=>{const a=Store.accounts().find(a=>a.name==='差旅信用卡');return [a.type,a.opening];}),['liability',1204]);
  await close();
  await nav('bills');
  await page.getByLabel('流水日期范围').selectOption('all');
  const filter=()=>page.getByRole('button',{name:'筛选账单'}).click();
  const apply=()=>sheet.getByRole('button',{name:'应用筛选'}).click();
  const rows=page.locator('.j-results .j-item');
  await filter();
  await sheet.getByLabel('指定金额').fill('0.20');
  await apply();
  assert.equal(await rows.count(),1);
  assert.match(await rows.innerText(),/手续费/);
  await filter();
  await sheet.getByLabel('金额匹配方式').selectOption('range');
  await sheet.getByLabel('最低金额').fill('10');
  await sheet.getByLabel('最高金额').fill('9');
  await apply();
  assert.match(await sheet.locator('.amount-error').innerText(),/小于/);
  await sheet.getByLabel('最高金额').fill('19.8');
  await apply();
  assert.equal(await rows.count(),2);
  await page.getByRole('button',{name:'隐藏金额'}).click();
  assert.doesNotMatch(await page.locator('.report-filter').innerText(),/19\.8|10/);
  await page.getByRole('button',{name:'清除筛选'}).click();
  assert.equal(await rows.count(),4);
});
