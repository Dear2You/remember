'use strict';
const assert=require('node:assert/strict');
const path=require('node:path');
const test=require('node:test');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');

test('预算节奏可点选日期核对消费，支持键盘、历史月份与隐藏金额',async t=>{
  const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL || undefined});
  t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:320,height:740},reducedMotion:'reduce'});
  await page.clock.setFixedTime(new Date(2028,1,13,12));
  await page.goto(pathToFileURL(path.resolve(process.env.APP_HTML || 'app/index.html')).href);
  await page.evaluate(()=>{
    Store.saveMoneyPlan({month:'2028-02',limitMinor:29000,saveMinor:0,repeat:true});
    const book=Store.addBook({name:'其他消费'});
    Store.addTransaction({type:'out',date:'2028-02-01',accountId:'acc-bank',amountMinor:1550,note:'样例餐费'});
    Store.addTransaction({type:'out',bookId:book.id,date:'2028-02-13',accountId:'acc-credit',amountMinor:2450,note:'样例书本'});
    Store.addTransaction({type:'transfer',date:'2028-02-13',fromId:'acc-wx',toId:'acc-credit',amountMinor:1200,feeMinor:12,feeMode:'extra'});
    Store.addTransaction({type:'out',date:'2028-02-28',accountId:'acc-bank',amountMinor:10990,note:'未来记账日期'});
  });
  await page.locator('.home-money header [data-dest="money"]').click();
  const section=page.getByRole('region',{name:'消费节奏'}),slider=section.getByRole('slider');
  await page.getByText(/月度汇总含 1 笔未来日期支出/).waitFor();
  assert.equal(await slider.getAttribute('aria-valuemax'),'13');
  assert.equal(await section.locator('.j-pace-total').innerText(),'¥40.12');
  assert.match(await section.locator('.pace-reading').innerText(),/均摊至当日 ¥130/);
  await section.getByRole('button',{name:'2 笔明细 ›'}).click();
  const sheet=page.locator('#sheetRoot');
  assert.equal(await sheet.locator('[data-money-tx]').count(),2);
  assert.match(await sheet.innerText(),/样例书本/);
  assert.match(await sheet.innerText(),/手续费/);
  await sheet.locator('.sheet-close').click();
  await slider.scrollIntoViewIfNeeded();
  const box=await slider.boundingBox();
  await slider.click({position:{x:Math.round(box.width/29),y:14}});
  assert.equal(await slider.getAttribute('aria-valuenow'),'1');
  assert.equal(await section.locator('.j-pace-total').innerText(),'¥15.5');
  await slider.press('ArrowRight');
  assert.equal(await section.getByRole('button',{name:'当天无支出'}).isDisabled(),true);
  await slider.evaluate(el=>el.scrollIntoView({block:'center',behavior:'instant'}));
  const dragBox=await slider.boundingBox();
  await page.mouse.move(dragBox.x+dragBox.width*2/29,dragBox.y+18);
  await page.mouse.down();
  await page.mouse.move(dragBox.x+dragBox.width*8/29,dragBox.y+18,{steps:4});
  assert.equal(await slider.getAttribute('aria-valuenow'),'8');
  await page.mouse.up();
  await slider.press('End');
  assert.equal(await section.getByRole('button',{name:'查看后一天'}).isDisabled(),true);
  await page.getByRole('button',{name:'下个月',exact:true}).click();
  await section.getByText(/这个月尚未开始/).waitFor();
  assert.equal(await slider.count(),0);
  await page.getByRole('button',{name:'上个月',exact:true}).click();
  await page.getByRole('button',{name:'上个月',exact:true}).click();
  await section.getByRole('button',{name:'设置消费上限 ›'}).click();
  assert.equal(await sheet.locator('.j-month').inputValue(),'2028-01');
  await sheet.locator('.sheet-close').click();
  await page.getByRole('button',{name:'下个月',exact:true}).click();
  await page.evaluate(()=>Store.mutate(d=>{d.settings.hideAmount=true;}));
  await section.getByText('金额已隐藏').waitFor();
  assert.equal(await slider.count(),0);
  assert.doesNotMatch(await section.innerHTML(),/40\.12|2450|pace-actual/);
});
