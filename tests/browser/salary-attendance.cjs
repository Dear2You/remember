'use strict';

const assert=require('node:assert/strict');
const test=require('node:test');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');

test('跨月补记按日期核对，保留旧记录，月薪实际工时单独登记',async t=>{
  const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL || undefined});
  t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:320,height:720},timezoneId:'Asia/Shanghai',reducedMotion:'reduce'});
  await page.clock.setFixedTime(new Date('2026-11-05T17:00:00+08:00'));
  await page.goto(pathToFileURL(path.resolve(process.env.APP_HTML || 'app/index.html')).href);
  const {plan,next}=await page.evaluate(()=>{
    const project='联培样例';
    Store.addWork({date:'2026-10-30',project,payMode:'day',paidDays:1,dailyRateMinor:20000});
    Store.addWork({date:'2026-11-03',project:'晚间家教',hours:2,rate:30});
    const input={project,calendar:'custom',cycleStartDay:21,cycleConfirmed:true,employmentStart:'2026-10-22',baseMinor:100001};
    const p=Store.saveSalaryPlan({...input,month:'2026-11',dates:['2026-10-21','2026-10-23','2026-10-30','2026-11-02','2026-11-03','2026-11-04','2026-11-05','2026-11-06']});
    const next=Store.saveSalaryPlan({...input,month:'2026-12',dates:['2026-11-23']});
    Store.setSalaryAttendance(p.id,['2026-10-23'],.5,'原有半天');
    Store.setSalaryAttendance(p.id,['2026-11-02'],0);
    return {plan:p.id,next:next.id};
  });
  await page.locator('#tabbar [data-route="worktime"]').click();
  const card=page.locator('.salary-project'), sheet=page.locator('.sheet-body');
  await card.locator('[data-batch]:visible').click();
  const checks=sheet.getByRole('checkbox');
  assert.deepEqual(await checks.evaluateAll(xs=>xs.map(x=>x.value)),['2026-11-03','2026-11-04','2026-11-05']);
  assert.equal(await sheet.locator('input:checked').count(),0);
  assert.equal(await sheet.getByRole('button',{name:'核对并保存'}).isEnabled(),false);
  await sheet.getByText('已有同项目工时 · 1 天').click();
  assert.equal(await sheet.locator('[data-review-date]').first().getAttribute('data-review-date'),'2026-10-30');
  await sheet.getByRole('button',{name:'选到昨天'}).click();
  assert.equal(await sheet.locator('input:checked').count(),2);
  await sheet.getByRole('button',{name:'全选'}).click();
  assert.equal(await sheet.locator('input:checked').count(),3);
  await sheet.getByRole('button',{name:'清空'}).click();
  await sheet.getByRole('button',{name:'选到昨天'}).click();
  await sheet.getByRole('combobox').selectOption('0.5');
  assert.match(await sheet.getByRole('status').innerText(),/已选 2 天.*新增已计工资 ¥125.*预计工资减少 ¥125/);
  await sheet.getByRole('button',{name:'核对并保存'}).click();
  await page.evaluate(id=>Store.setSalaryAttendance(id,['2026-11-03'],0),plan);
  await page.locator('#dialogRoot').getByRole('button',{name:'保存出勤'}).click();
  await sheet.locator('input[value="2026-11-03"]').waitFor({state:'detached'});
  const read=()=>page.evaluate(id=>Store.data.worktimes.filter(w=>w.salaryMonthId===id).map(w=>[w.date,w.paidDays,w.hours]),plan);
  assert.deepEqual(await read(),[['2026-10-23',.5,null],['2026-11-02',0,null],['2026-11-03',0,null]]);
  await sheet.getByRole('button',{name:'选到昨天'}).click();
  await sheet.getByRole('combobox').selectOption('0.5');
  await sheet.getByRole('button',{name:'核对并保存'}).click();
  await page.locator('#dialogRoot').getByRole('button',{name:'保存出勤'}).click();
  await sheet.waitFor({state:'hidden'});
  const tile=page.locator('.work-grid [data-date="2026-11-04"]');
  assert.match(await tile.innerText(),/0.5天/);
  const openDay=async()=>{await tile.click();await sheet.locator('[data-attendance="'+plan+'"]').click();};
  await openDay();
  await sheet.getByLabel('实际工时（小时）').fill('4.25');
  await sheet.getByRole('button',{name:'保存出勤'}).click();
  await sheet.waitFor({state:'hidden'});
  assert.match(await tile.innerText(),/4.25h/);
  assert.deepEqual((await read()).at(-1),['2026-11-04',.5,4.25]);
  await openDay();
  await sheet.getByLabel('实际工时（小时）').fill('25');
  await sheet.getByRole('button',{name:'保存出勤'}).click();
  assert.deepEqual((await read()).at(-1),['2026-11-04',.5,4.25]);
  await sheet.getByRole('button',{name:/缺勤一天/}).click();
  assert.equal(await sheet.getByLabel('实际工时（小时）').isVisible(),false);
  await sheet.getByRole('button',{name:'保存出勤'}).click();
  await sheet.waitFor({state:'hidden'});
  assert.deepEqual((await read()).at(-1),['2026-11-04',0,null]);
  await card.locator('select.j-salary-cycle').selectOption(next);
  await card.getByRole('button',{name:'本期到账 ›'}).click();
  assert.match(await page.locator('.sheet-title').innerText(),/联培样例.*2026年12月/);
  assert.match(await sheet.innerText(),/2026-11-21 至 2026-12-20/);
  assert.equal(await page.evaluate(()=>Store.data.transactions.length),0);
});
