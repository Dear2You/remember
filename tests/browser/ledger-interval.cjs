'use strict';

const assert = require('node:assert/strict');
const test = require('node:test');
const path = require('node:path');
const fs = require('node:fs/promises');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');

test('自选跨月流水及工资期，保留筛选并导出全部匹配记录', async t => {
  const browser = await chromium.launch({channel:process.env.BROWSER_CHANNEL || undefined});
  t.after(() => browser.close());
  const page = await browser.newPage({viewport:{width:320,height:700},reducedMotion:'reduce'});
  await page.clock.install({time:new Date(2026,10,23,12)});
  await page.goto(pathToFileURL(path.resolve(process.env.APP_HTML || 'app/index.html')).href);
  await page.evaluate(() => {
    const expense = Store.rootCategories('out')[0];
    const common = {bookId:'book-life',accountId:'acc-wx',type:'out',categoryId:expense.id,amountMinor:1250};
    Store.saveSalaryPlan({project:'联培样例',month:'2026-12',baseMinor:600000,cycleStartDay:21,cycleConfirmed:true,
      dates:['2026-11-23','2026-12-01'],calendar:'custom'});
    Store.addTransaction({...common,date:'2026-10-31',note:'@采购,月底'});
    for (let i=0;i<60;i++) Store.addTransaction({...common,date:'2026-11-01',note:'采购食材'});
    Store.addTransaction({...common,date:'2026-11-01',note:'其他'});
    Store.addTransaction({...common,date:'2026-11-02',note:'采购区间外'});
    Store.addTransaction({...common,date:'2026-11-23',note:'当期采购'});
    window.AndroidBridge = {saveDocument:(name,csv,isCsv) => {window.testExport = {name,csv,isCsv};}};
  });
  await page.locator('#tabbar [data-route="bills"]').click();
  const scope = page.getByLabel('流水日期范围',{exact:true});
  const sheet = page.locator('.sheet-body');
  const search = page.getByRole('searchbox');
  await search.fill('采购');
  await scope.selectOption('custom');
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  assert.equal(await scope.inputValue(),'period');
  await scope.selectOption('custom');
  const start = sheet.getByLabel('开始日期'), end = sheet.getByLabel('结束日期');
  await start.fill('2026-11-02');
  await end.fill('2026-11-01');
  await sheet.getByRole('button',{name:'查看这段流水'}).click();
  assert.match(await sheet.innerText(),/结束日期不能早于开始日期/);
  await start.fill('2026-10-31');
  await sheet.getByRole('button',{name:'查看这段流水'}).click();
  assert.equal(await scope.inputValue(),'custom');
  assert.equal(await page.locator('.j-results .j-item').count(),60);
  assert.match(await page.locator('.ledger-caption').innerText(),/61 笔/);
  await page.getByRole('button',{name:'导出流水'}).click();
  assert.match(await page.getByRole('alertdialog').innerText(),/导出这 61 笔/);
  await page.getByRole('button',{name:'保存 CSV'}).click();
  const file = await page.evaluate(() => window.testExport);
  assert.match(file.name,/2026-10-31_2026-11-01\.csv/);
  assert.equal(file.isCsv,true);
  assert.equal(file.csv.split('\r\n').length,62);
  assert.match(file.csv,/"'@采购,月底"/);
  assert.doesNotMatch(file.csv,/采购区间外|当期采购|,其他,/);
  await search.fill('区间外');
  assert.equal(await page.locator('.j-export-range').count(),0);
  await search.fill('采购');
  await page.getByRole('button',{name:'隐藏金额'}).click();
  assert.equal(await page.locator('.j-export-range').count(),0);
  await page.getByRole('button',{name:'修改流水起止日期'}).click();
  await sheet.getByRole('button',{name:'联培样例 · 本工资期'}).click();
  assert.deepEqual([await start.inputValue(),await end.inputValue()],['2026-11-21','2026-12-20']);
  await sheet.getByRole('button',{name:'查看这段流水'}).click();
  assert.equal(await page.locator('.j-results .j-item').count(),1);
  await page.getByRole('button',{name:'收支分析',exact:true}).click();
  assert.equal(await page.locator('.report-period').isVisible(),true);
  await page.getByRole('button',{name:'流水明细',exact:true}).click();
  assert.equal(await scope.inputValue(),'custom');
  assert.match(await page.locator('.j-results').innerText(),/当期采购/);
  await page.evaluate(() => {delete window.AndroidBridge;});
  await page.getByRole('button',{name:'显示金额'}).click();
  await page.getByRole('button',{name:'导出流水'}).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button',{name:'保存 CSV'}).click();
  const download = await downloadEvent;
  assert.match(download.suggestedFilename(),/2026-11-21_2026-12-20\.csv/);
  const content = await fs.readFile(await download.path(),'utf8');
  assert.equal(content.split('\r\n').length,2);
  assert.match(content,/当期采购/);
});
